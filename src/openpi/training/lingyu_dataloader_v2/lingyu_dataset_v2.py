"""Torch Dataset sampling randomly by global sample number: episode_index.parquet + Iceberg data files -> training samples.

Sampling pipeline (numbering matches the global index generated by build_sample_idx.py one to one)::
    global sample number i
      -> episode_index.parquet: sample_offset <= i < sample_offset + num_samples
      -> (the episode's data_file, row_group, and its sample_idx within the episode)
      -> read that row's samples column via read_row_group directly, converting only samples[sample_idx] into Python objects
      -> {topic: {msg_type, msg_def, log_time, locations}}
      -> all locations of all topics are grouped by their chunk; those within MERGE_GAP merge into one segment,
         one S3 range request per segment, submitted to a thread pool for parallel reads, slicing and deserialization, then regrouped by topic
      -> video topics go to the GPU decode process; decoding, mono-eye cropping and scaling all happen on the GPU;
         state/action topics are concatenated into vectors in model_config's order

__getitem__ returns a single-frame sample without a leading frame dimension (feedable to RepackTransform directly)::
    {"observation": {"images": {"left_color": (140, 224, 3) uint8, "head_camera": (224, 224, 3) uint8, ...},
                     "state":  (state_dim,) float32},
     "action": (action_horizon or ACTION_CHUNK_LENGTH, action_dim) float32,
     "prompt": str}
Images are already mono-cropped (TeleavatarInputs) and aspect-preserving scaled (ResizeImages's resize_with_pad) on the GPU per openpi's transforms,
so these two downstream steps pass such images through / only pad black borders; openpi configs stay unchanged, and no full 4K frame decoding or scaling happens in workers.
Crop and scale parameters are not configured separately; load_video_decode_config() takes them from openpi's DataConfig.
uint8 HWC is not converted to float; state/action are concatenated as-is, without normalization or unit conversion.

No Iceberg scan: it would traverse all manifests and candidate files' footers to find one row, and convert the whole
episode's thousand-plus samples into Python objects; the index already records the physical location, so just read that row group.
The fetcher is module-level: when the DataLoader starts workers via forkserver, each worker holds its own forked copy and no handle ever crosses a process boundary.
The thread pool is created and closed per sample: no resident threads remain, so workers forked by the DataLoader never inherit a stale pool.

Usage::
    video_key_to_crop, image_resolution = load_video_decode_config(data_config)
    dataset = LingyuDatasetV2(data_config.iceberg_dir, video_key_to_crop=video_key_to_crop,
                              image_resolution=image_resolution)
"""
from __future__ import annotations

import logging
from bisect import bisect_right
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import duckdb
import numpy as np
import pyarrow.parquet as pq
import torch

from openpi.policies import teleavatar_v2_policy
from openpi.training.lingyu_dataloader_v2.build_sample_idx import (
    GLOBAL_INDEX_NAME,
    WAREHOUSE_DIR)
from openpi.training.lingyu_dataloader_v2.mcap_config.config import (
    load_mcap_video_topics_gop,
    load_mcap_state_and_action_topics_fields)
from openpi.training.lingyu_dataloader_v2.model_config.config import (
    load_action_chunk_length,
    load_state_and_action_concat)
from openpi.training.lingyu_dataloader_v2.utils._mcap_utils import (
    RECORD_PREFIX,
    S3_MAX_POOL_CONNECTIONS)
from openpi.training.lingyu_dataloader_v2.utils.mcap_message_fetcher import (
    MCAP_Message_Fetcher)
from openpi.training.lingyu_dataloader_v2.utils.ros2_message_filter import (
    ros2_message_filter)
from openpi.training.lingyu_dataloader_v2.utils.video_frame_decoder import (
    gpu_decode_current_frames,
    start_gpu_decoders)
import openpi.transforms as _transforms


# Constants
# Map Standard Video Topics to the names used in openpi code
VIDEO_TOPIC_TO_KEY = {
    '/left/color/image_raw/ffmpeg': 'left_color',
    '/right/color/image_raw/ffmpeg': 'right_color',
    '/xr_video_topic/ffmpeg': 'head_camera',
}
# Threads reading messages in parallel within one sample. In-flight requests across all workers = num_workers x this value;
# 256 workers x 8 threads (2048 concurrent) overwhelms the OSS gateway with constant read timeouts and TooManyRequests, so it is reduced to 2 (512 concurrent)
SAMPLE_FETCH_WORKERS = 2
# Adjacent messages within one chunk merge into one range read when their gap does not exceed this. One sample's state/action
# has about 122 locations across 6 chunks, merging into about 20 requests (from 244) and about 1.1MiB; larger means fewer requests but more wasted bytes downloaded
MERGE_GAP = 64 * 1024
# Only these columns are needed for sampling from the global index
INDEX_COLUMNS = ("prompt", "episode_id", "num_samples", "data_file", "row_group", "sample_offset")

logger = logging.getLogger(__name__)

fetcher = MCAP_Message_Fetcher()


def load_video_decode_config(data_config) -> tuple[dict[str, tuple[str, bool]], tuple[int, int]]:
    """Extract the image transform parameters GPU decoding must replicate from openpi's DataConfig; returns ({camera name: (which eye to keep, rotate 180° first)}, (height, width)).

    The eye-selection rule comes from teleavatar_v2_policy.STEREO_EYES, rotation from TeleavatarInputs.rotate_head_camera (like it, only the head camera rotates),
    and (height, width) from ResizeImages in model_transforms; change these configs and GPU decoding changes with them, never diverging from openpi's transforms.
    """
    teleavatar_inputs = next(transform for transform in data_config.data_transforms.inputs
                             if isinstance(transform, teleavatar_v2_policy.TeleavatarInputs))
    resize_images = next(transform for transform in data_config.model_transforms.inputs
                         if isinstance(transform, _transforms.ResizeImages))
    video_key_to_crop = {key: (eye, key == "head_camera" and teleavatar_inputs.rotate_head_camera)
                         for key, eye in teleavatar_v2_policy.STEREO_EYES.items()}
    return video_key_to_crop, (resize_images.height, resize_images.width)


def load_episode_index(warehouse_dir: str) -> list[dict]:
    """Read episode_index.parquet, returning the episode list sorted by sample_offset ascending."""
    index_path = Path(warehouse_dir, GLOBAL_INDEX_NAME)
    assert index_path.exists(), f"没有 {index_path}, 请先运行 build_sample_idx.py"
    index_columns = duckdb.sql(f"SELECT * FROM '{index_path}' LIMIT 0").columns
    assert set(INDEX_COLUMNS) <= set(index_columns), \
        f"{index_path} 缺少 {set(INDEX_COLUMNS) - set(index_columns)}, 请运行 build_sample_idx.py --index-only 重建索引"
    index_rows = duckdb.sql(f"SELECT {', '.join(INDEX_COLUMNS)} FROM '{index_path}' "
                            f"ORDER BY sample_offset").fetchall()
    return [dict(zip(INDEX_COLUMNS, row)) for row in index_rows]


def load_sample_topics(data_file: str, row_group: int, sample_idx: int) -> dict[str, dict]:
    """Read the row group this episode lives in, converting only the sample_idx-th sample into Python objects."""
    samples_column = pq.ParquetFile(data_file).read_row_group(row_group, columns=["samples"]).column(0)
    # The writer emits one episode per row group, so there is exactly one row here
    assert len(samples_column) == 1, f"{data_file} 的 row group {row_group} 有 {len(samples_column)} 行"
    episode_samples = samples_column[0].values      # Arrow array of all the episode's samples, not converted to Python
    assert 0 <= sample_idx < len(episode_samples), \
        f"sample_idx={sample_idx} 越界, 该 episode 只有 {len(episode_samples)} 个 sample, 索引与数据不同步"
    return episode_samples[sample_idx].as_py()


def group_location_spans(flat_locations: list[tuple[str, dict]]) -> list[tuple[str, int, list[tuple[int, dict]]]]:
    """Group flattened (topic, location) pairs by their chunk, sort within groups by offset, and merge those within MERGE_GAP into segments.

    Returns [(mcap_url, chunk_file_offset, [(flat_idx, location), ...]), ...]; one segment corresponds to one S3 range request;
    flat_idx is the location's index in flat_locations.
    """
    chunk_locations = dict()
    for flat_idx, (_, location) in enumerate(flat_locations):
        chunk_key = (location["mcap_url"], location["chunk_file_offset"])
        chunk_locations.setdefault(chunk_key, []).append((flat_idx, location))

    location_spans = []
    for (mcap_url, chunk_file_offset), chunk_items in chunk_locations.items():
        chunk_items.sort(key=lambda item: item[1]["uncompressed_byte_offset"])
        span_end = 0
        for item_idx, (flat_idx, location) in enumerate(chunk_items):
            location_start = location["uncompressed_byte_offset"]
            location_end = location_start + RECORD_PREFIX + location["record_length"]
            # First entry of this chunk, or more than MERGE_GAP from the previous segment's end: start a new segment
            if item_idx == 0 or location_start - span_end > MERGE_GAP:
                location_spans.append((mcap_url, chunk_file_offset, []))
                span_end = location_end
            location_spans[-1][2].append((flat_idx, location))
            span_end = max(span_end, location_end)
    return location_spans


def fetch_sample_messages(sample_topics: dict[str, dict],
                          thread_pool: ThreadPoolExecutor) -> dict[str, list]:
    """Merge all locations of all topics of one sample into segments by chunk, each segment submitted to the thread pool as one task for parallel read and deserialization.

    Returns {topic: [ros2 message, ...]}; within each topic the order matches that topic's locations order.
    """
    flat_locations = [(topic, location) for topic, message in sample_topics.items()
                      for location in message["locations"]]
    location_spans = group_location_spans(flat_locations)
    # Submit segments ordered by total message bytes, largest first: long-transferring big segments start early instead of queuing last and stretching total time
    location_spans.sort(key=lambda span: sum(location["record_length"] for _, location in span[2]), reverse=True)
    logger.debug(f"{len(flat_locations)} 个 location 合并为 {len(location_spans)} 次 S3 请求")

    span_futures = []
    for mcap_url, chunk_file_offset, span_items in location_spans:
        span_messages = [(sample_topics[flat_locations[flat_idx][0]]["msg_type"],
                          sample_topics[flat_locations[flat_idx][0]]["msg_def"],
                          location["uncompressed_byte_offset"], location["record_length"])
                         for flat_idx, location in span_items]
        span_futures.append(([flat_idx for flat_idx, _ in span_items], thread_pool.submit(
            fetcher.fetch_span_messages, mcap_url, chunk_file_offset, span_messages)))

    # Segment results are placed back by flat_idx into their pre-flattening positions, so each topic's message order matches locations
    flat_messages = [None] * len(flat_locations)
    for flat_idxs, span_future in span_futures:
        for flat_idx, ros2_message in zip(flat_idxs, span_future.result(), strict=True):
            flat_messages[flat_idx] = ros2_message
    assert all(ros2_message is not None for ros2_message in flat_messages), "有 location 未被任何一段读取"

    topic_messages = {topic: [] for topic in sample_topics}
    for (topic, _), ros2_message in zip(flat_locations, flat_messages):
        topic_messages[topic].append(ros2_message)
    return topic_messages


def filter_sample_messages(sample_topics: dict[str, dict], gpu_decoder_address: str | None = None,
                           video_key_to_crop: dict[str, tuple[str, bool]] | None = None,
                           image_resolution: tuple[int, int] | None = None) -> dict[str, np.ndarray | list[dict]]:
    """
    Takes one sample's {topic: {msg_type, msg_def, log_time, locations}} as input,
    and outputs {video topic: current frame array, state/action topic: [{field name: 1-D array}, ...]}.

    A video topic's locations are one whole GOP, handed to the GPU decode process at gpu_decoder_address, with only the last frame (the current frame) returned,
    mono-cropped (and rotated) per video_key_to_crop and scaled per image_resolution, both taken from load_video_decode_config();
    each location of a state/action topic is an independent message, deserialized and field-selected per config,
    so state yields a length-1 list and action a length-ACTION_CHUNK_LENGTH list (the index being the future step number).
    All locations are read in parallel first, then each video is sent once more to the decode process to decode in parallel, finally merged into one dict.
    When gpu_decoder_address is None, video topics are neither read from S3 nor decoded (compute_norm_stats only needs state/action).
    """
    video_topics_gop = load_mcap_video_topics_gop() if gpu_decoder_address else {}
    state_and_action_fields = load_mcap_state_and_action_topics_fields()
    # None marks a placeholder padded to align all rows; topics unused in the config are not read
    used_topics = {topic: message for topic, message in sample_topics.items()
                   if message is not None and (topic in video_topics_gop or topic in state_and_action_fields)}

    with ThreadPoolExecutor(max_workers=SAMPLE_FETCH_WORKERS) as thread_pool:
        topic_messages = fetch_sample_messages(used_topics, thread_pool)
    topic_data = {topic: [ros2_message_filter(topic, ros2_message) for ros2_message in ros2_messages]
                  for topic, ros2_messages in topic_messages.items() if topic in state_and_action_fields}

    # One sample's video streams combine into a single request; the decode process decodes them in parallel
    video_topics = [topic for topic in topic_messages if topic in video_topics_gop]
    video_requests = [(topic, topic_messages[topic][0].encoding, *video_key_to_crop[VIDEO_TOPIC_TO_KEY[topic]],
                       image_resolution, [bytes(packet.data) for packet in topic_messages[topic]])
                      for topic in video_topics]
    if video_requests:
        topic_data.update(zip(video_topics, gpu_decode_current_frames(gpu_decoder_address, video_requests)))
    return topic_data


def concat_vector(topic_data: dict, concat_config: tuple, step_idx: int) -> np.ndarray:
    """Concatenate the step_idx-th step's 1-D vector in model_config's (topic, field) order."""
    return np.concatenate([topic_data[topic][step_idx][field_name]
                           for topic, field_name in concat_config]).astype(np.float32)


class LingyuDatasetV2(torch.utils.data.Dataset):
    """Sample randomly by global sample number: the index comes from episode_index.parquet, data from Iceberg data files + mcaps.

    __init__ reads only the global index, opening no data files or mcaps, so the object holds only paths and integers and can be pickled safely into
    the DataLoader's worker processes; data files are opened per sample on demand, and the decompression cache is built per process at first sample.
    """

    def __init__(self, warehouse_dir: str = WAREHOUSE_DIR, load_images: bool = True,
                 video_key_to_crop: dict[str, tuple[str, bool]] | None = None,
                 image_resolution: tuple[int, int] | None = None,
                 action_horizon: int | None = None):
        self.warehouse_dir = warehouse_dir
        # False: take only state/action; the output images is an empty dict
        self.load_images = load_images
        # When reading images, GPU crop/scale parameters are required, always taken from openpi configs via load_video_decode_config(data_config)
        assert not load_images or (video_key_to_crop and image_resolution), \
            "load_images=True 时须传入 load_video_decode_config(data_config) 返回的 video_key_to_crop 与 image_resolution"
        self.video_key_to_crop = video_key_to_crop
        self.image_resolution = image_resolution
        self.episodes = load_episode_index(warehouse_dir)
        # Episodes' start offsets in ascending order, for bisect to look up an episode from a global sample number
        self.sample_offsets = [episode["sample_offset"] for episode in self.episodes]
        self.num_samples = self.sample_offsets[-1] + self.episodes[-1]["num_samples"]
        self.state_concat, self.action_concat = load_state_and_action_concat()
        self.action_topics = frozenset(topic for topic, _ in self.action_concat)
        # Training only needs the first action_horizon action steps; the index holds at most ACTION_CHUNK_LENGTH steps, and a horizon beyond that has no data to take
        assert action_horizon is None or action_horizon <= load_action_chunk_length(), \
            f"action_horizon={action_horizon} 超过索引的动作序列长度 ACTION_CHUNK_LENGTH={load_action_chunk_length()}, " \
            "请重跑 build_sample_idx.py 或调小模型配置的 action_horizon"
        self.action_horizon = action_horizon
        # Start the GPU decode processes in the main process first; the object stores only their address strings, so it still pickles into workers
        self.gpu_decoder_addresses = start_gpu_decoders() if load_images else []

        logger.info(f"{self.num_samples} samples in {len(self.episodes)} episodes "
                    f"({len(set(e['prompt'] for e in self.episodes))} prompts) from {warehouse_dir}, "
                    f"load_images={load_images}")

    def __len__(self):
        """Total sample count across all prompts, taken directly from the global index."""
        return self.num_samples

    def locate_episode(self, index: int) -> dict:
        """Global sample number -> the index row (INDEX_COLUMNS) of its episode."""
        assert 0 <= index < self.num_samples, f"sample 编号 {index} 越界 [0, {self.num_samples})"
        # sample_offset is ascending and contiguously covering, so the sample falls in the last episode whose offset is <= index
        return self.episodes[bisect_right(self.sample_offsets, index) - 1]

    def locate_sample(self, index: int) -> tuple[str, str, int]:
        """Global sample number -> (prompt, episode_id, its sample_idx within the episode)."""
        episode = self.locate_episode(index)
        return episode["prompt"], episode["episode_id"], index - episode["sample_offset"]

    def __getitem__(self, index: int) -> dict:
        """Fetch one sample: look up the episode's physical location -> decode/deserialize -> assemble into the model's state/action."""
        episode = self.locate_episode(index)
        prompt = episode["prompt"]
        # Workers take turns on each GPU's decode process by number; sampling in the main process (num_workers=0) uses the first
        worker_info = torch.utils.data.get_worker_info()
        gpu_decoder_address = self.gpu_decoder_addresses[
            (worker_info.id if worker_info else 0) % len(self.gpu_decoder_addresses)] if self.load_images else None
        sample_topics = load_sample_topics(episode["data_file"], episode["row_group"], index - episode["sample_offset"])
        # Take only the first action_horizon action steps, trimming extra locations before reading the mcap to save S3 traffic
        if self.action_horizon is not None:
            for action_topic in self.action_topics:
                sample_topics[action_topic]["locations"] = sample_topics[action_topic]["locations"][:self.action_horizon]
        topic_data = filter_sample_messages(
            sample_topics, gpu_decoder_address, self.video_key_to_crop, self.image_resolution)

        # The action step count is decided by the data itself (the number of locations, i.e. action_horizon after truncation)
        action_steps = len(topic_data[self.action_concat[0][0]])
        state = concat_vector(topic_data, self.state_concat, 0)
        action = np.stack([concat_vector(topic_data, self.action_concat, step_idx)
                           for step_idx in range(action_steps)])

        return {
            "observation": {
                "images": {key: topic_data[topic]
                           for topic, key in VIDEO_TOPIC_TO_KEY.items() if topic in topic_data},
                "state": torch.from_numpy(state),
            },
            "action": torch.from_numpy(action),
            "prompt": prompt,
        }


